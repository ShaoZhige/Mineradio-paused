#!/usr/bin/env node
'use strict';

/**
 * 从 docs/API-CONTRACT.json 生成 `src-tauri/src/bridge/shim.js`。
 *
 *   node scripts/gen-shim.js           生成
 *   node scripts/gen-shim.js --check   只比对，不一致退出 1（CI 用）
 *
 * 为什么生成而不是手写：契约里 130 个桥项（116 顶层键 + halo 的 15 个子方法），手写必然漏。
 * 漏掉的那个不会报错、不会红测试 —— 前端只会静默变成 `undefined is not a function`。
 *
 * shim 是 P1 的"占位桥"：每个方法都如实返回
 * `{ok:false, reason:'NOT_IMPLEMENTED', api:'<名字>'}`，让前端走它自己的错误分支，
 * 而不是在 `desktopWindow` 为 undefined 时直接崩在第一个调用的地方。
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CONTRACT_PATH = path.join(ROOT, 'docs', 'API-CONTRACT.json');
const OUT_PATH = path.join(ROOT, 'src-tauri', 'src', 'bridge', 'shim.js');

// 这些值由 Rust 侧在注入时替换成真实值。写成占位符而不是模板字符串，
// 是为了生成结果里不出现 `${` —— 那个文件本身会被塞进 WebView 执行。
const PORT_PLACEHOLDER = '__MINERADIO_PORT__';
const RELEASE_PLACEHOLDER = '__MINERADIO_SYSTEM_RELEASE__';

function jsString(value) {
  return JSON.stringify(String(value));
}

function buildShim(contract) {
  const entries = contract.bridge || [];
  if (entries.length === 0) throw new Error('契约里没有 bridge 条目，先跑 npm run contract:extract');

  // 顶层树：`halo.getConfig` 要落成 `halo: { getConfig: ... }`
  const tree = new Map();
  for (const entry of entries) {
    const parts = entry.name.split('.');
    let node = tree;
    for (let i = 0; i < parts.length - 1; i += 1) {
      if (!node.has(parts[i])) node.set(parts[i], new Map());
      node = node.get(parts[i]);
    }
    node.set(parts[parts.length - 1], entry);
  }

  const lines = [];
  let stubCount = 0;
  let eventCount = 0;
  let syncCount = 0;

  function emit(map, indent) {
    const pad = ' '.repeat(indent);
    for (const [key, value] of map) {
      if (value instanceof Map) {
        lines.push(`${pad}${key}: {`);
        emit(value, indent + 2);
        lines.push(`${pad}},`);
        continue;
      }
      const api = jsString(value.name);
      switch (value.kind) {
        case 'event':
          eventCount += 1;
          // 事件订阅返回退订函数；P1 没有真事件，所以退订是空操作。
          lines.push(`${pad}${key}: function (callback) { return subscribe(${api}, callback); },`);
          break;
        case 'send':
          lines.push(`${pad}${key}: function () { return sendOnce(${api}, arguments); },`);
          stubCount += 1;
          break;
        case 'sendSync':
          syncCount += 1;
          lines.push(`${pad}${key}: function () { return syncOnce(${api}); },`);
          break;
        case 'clipboard':
          lines.push(`${pad}${key}: function () { return promiseOnce(${api}); },`);
          stubCount += 1;
          break;
        case 'value':
          if (value.name === 'isDesktop') lines.push(`${pad}${key}: true,`);
          else if (value.name === 'systemRelease') lines.push(`${pad}${key}: SYSTEM_RELEASE,`);
          else lines.push(`${pad}${key}: null,`);
          break;
        default:
          lines.push(`${pad}${key}: function () { return promiseOnce(${api}); },`);
          stubCount += 1;
      }
    }
  }

  emit(tree, 2);

  return `// 自动生成，请勿手改 —— 改 docs/API-CONTRACT.json 后跑 npm run shim:gen
// Generated by scripts/gen-shim.js. Bridge items: ${entries.length} (top-level keys ${contract.counts.bridgeTopLevel}).
//
// P1 占位桥：所有方法都返回 NOT_IMPLEMENTED，并在 __mineradioBridge.calls 里记账，
// P3 逐个替换成 tauri invoke 时，这张记账表就是"还有哪些没搬"的清单。
(function () {
  'use strict';
  if (window.desktopWindow) return;

  var PORT = ${PORT_PLACEHOLDER};
  var SYSTEM_RELEASE = ${jsString(RELEASE_PLACEHOLDER)};
  var calls = [];
  var pending = {};

  function record(api) {
    var hit = pending[api];
    if (hit) return;
    pending[api] = true;
    calls.push(api);
  }

  function promiseOnce(api) {
    record(api);
    return Promise.resolve({ ok: false, reason: 'NOT_IMPLEMENTED', api: api });
  }

  function sendOnce(api, args) {
    record(api);
    // 单向发送没有返回值；参数丢掉是故意的，P3 接上真实通道时才开始用。
    return undefined;
  }

  function syncOnce(api) {
    record(api);
    return { ok: false, reason: 'NOT_IMPLEMENTED', api: api };
  }

  function subscribe(api, callback) {
    record(api);
    if (typeof callback !== 'function') return function () {};
    // 没有真事件，但要让订阅方拿到一个可调用的退订函数，否则 try/finally 里会炸。
    return function () {};
  }

  var desktopWindow = {
${lines.join('\n')}
  };

  Object.defineProperty(window, 'desktopWindow', { value: desktopWindow, writable: false, configurable: false });
  window.__mineradioBridge = {
    port: PORT,
    systemRelease: SYSTEM_RELEASE,
    calls: calls,
    // 便于 P3 对账：还差哪些方法没接
    missing: function () { return calls.slice(); },
  };
})();
`;
}

function main() {
  const check = process.argv.includes('--check');
  if (!fs.existsSync(CONTRACT_PATH)) {
    console.error('FAIL docs/API-CONTRACT.json 不存在，先跑 npm run contract:extract');
    process.exit(1);
  }
  const contract = JSON.parse(fs.readFileSync(CONTRACT_PATH, 'utf8'));
  const text = buildShim(contract);

  if (check) {
    if (!fs.existsSync(OUT_PATH)) {
      console.error('FAIL src-tauri/src/bridge/shim.js 不存在，先跑 npm run shim:gen');
      process.exit(1);
    }
    const current = fs.readFileSync(OUT_PATH, 'utf8').replace(/\r\n/g, '\n');
    if (current !== text) {
      console.error('FAIL shim 与契约不一致 —— 契约变了但 shim 没重新生成');
      process.exit(1);
    }
    console.log(`OK shim 与契约一致（${contract.bridge.length} 项）`);
    return;
  }

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, text, 'utf8');
  const lines = text.split('\n').length;
  console.log(`已写入 src-tauri/src/bridge/shim.js（${contract.bridge.length} 项 / ${lines} 行）`);
}

main();
